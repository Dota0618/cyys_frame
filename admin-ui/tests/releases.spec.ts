import { test, expect } from '@playwright/test';
import { login, chooseScope, direct } from './browser-support';

test('平台版本日期、附件上传、跨单位保留下载与解除关联', async ({ page }) => {
  await login(page, 'g4-release-editor'); await chooseScope(page, '单位 A');
  await page.getByRole('menuitem').filter({ hasText: '版本更新' }).click();
  await page.getByRole('button', { name: '新增版本', exact: true }).click();
  let form = page.getByRole('dialog', { name: '新增版本', exact: true });
  await form.getByRole('button', { name: '确 定' }).click();
  await expect(form.getByText('请选择更新日期', { exact: true })).toBeVisible();
  await form.getByLabel('版本号', { exact: true }).fill('9.0-test');
  await form.getByLabel('更新日期', { exact: true }).fill('2026-09-20');
  await form.getByLabel('更新日期', { exact: true }).press('Enter');
  await form.getByRole('combobox', { name: '版本类型' }).click();
  await page.locator('.ant-select-dropdown:visible').getByText('常规更新', { exact: true }).click();
  await form.getByLabel('更新说明', { exact: true }).fill('说明\n<script>作为文本</script>');
  const name = 'g4-browser-release.txt'; const bytes = Buffer.from('共享版本附件');
  await form.locator('input[type=file]').setInputFiles({ name, mimeType: 'text/plain', buffer: bytes });
  await expect(form.locator('li').filter({ hasText: name })).toBeVisible();
  await form.getByRole('button', { name: '确 定' }).click();
  await expect(form).not.toBeVisible();
  const root = '/api/admin/platform/releases';
  const id = (await direct(page, 'GET', `${root}?number=9.0-test`)).body.data.records[0].id;
  let detail = (await direct(page, 'GET', `${root}/${id}`)).body.data;
  expect(detail.release.dateUpdate).toBe('2026-09-20');
  const fileId = detail.attachments[0].id;
  await chooseScope(page, '单位 B');
  const row = page.locator(`tr[data-row-key="${id}"]`);
  await row.getByRole('button', { name: /编\s*辑/ }).click();
  form = page.getByRole('dialog', { name: '编辑版本' });
  await expect(form.locator('li').filter({ hasText: name })).toBeVisible();
  await form.getByRole('button', { name: '确 定' }).click();
  await expect(form).not.toBeVisible();
  await row.getByRole('button', { name: /详\s*情/ }).click();
  const viewer = page.getByRole('dialog', { name: '版本 9.0-test' });
  await expect(viewer).toContainText('<script>作为文本</script>');
  await expect(viewer.locator('script')).toHaveCount(0);
  const pending = page.waitForEvent('download'); await viewer.getByRole('button', { name, exact: true }).click();
  const file = await pending; const stream = await file.createReadStream(); const chunks: Buffer[] = [];
  for await (const chunk of stream) chunks.push(chunk);
  expect(Buffer.concat(chunks)).toEqual(bytes);
  await viewer.getByRole('button', { name: 'Close' }).click();
  await row.getByRole('button', { name: /编\s*辑/ }).click();
  await form.getByRole('button', { name: '移除关联' }).click();
  await form.getByRole('button', { name: '确 定' }).click();
  await expect(form).not.toBeVisible();
  detail = (await direct(page, 'GET', `${root}/${id}`)).body.data;
  expect(detail.attachments).toEqual([]);
  await row.getByRole('button', { name: /删\s*除/ }).click();
  await page.getByRole('tooltip').getByRole('button', { name: /删\s*除/ }).click();
  await expect(row).toHaveCount(0);
  await chooseScope(page, '单位 A');
  const remaining = await direct(page, 'GET', `/api/admin/files?search=${encodeURIComponent(name)}`);
  expect(remaining.status).toBe(200);
  expect(remaining.body.data.records).toEqual(expect.arrayContaining([expect.objectContaining({ id: fileId })]));
});
