import { test, expect } from '@playwright/test';
import { login, direct } from './browser-support';

test('地区层级、清空坐标、查询导出和删除使用真实后端', async ({ page }) => {
  await login(page, 'platform');
  await page.getByRole('menuitem').filter({ hasText: '地区参数' }).click();
  await expect(page.getByText('顶级地区列表', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '新增地区', exact: true }).click();
  let form = page.getByRole('dialog', { name: '新增地区', exact: true });
  await form.getByRole('button', { name: '确 定' }).click();
  await expect(form.getByText('请输入 1–20 个字符的地区名称')).toBeVisible();
  await form.getByLabel('地区名称', { exact: true }).fill('验收顶级地区');
  await form.getByLabel('地区编码', { exact: true }).fill('000001');
  await form.getByLabel('邮编', { exact: true }).fill('001234');
  await form.getByRole('spinbutton', { name: '经度', exact: true }).fill('120.5');
  await form.getByRole('button', { name: '确 定' }).click();
  await expect(form).not.toBeVisible();
  const root = '/api/admin/platform/regions';
  const parent = (await direct(page, 'GET', root)).body.data.records.find((r: { cityCode: string }) => r.cityCode === '000001');
  const row = page.locator(`tr[data-row-key="${parent.id}"]`);
  await row.getByRole('button', { name: /编\s*辑/ }).click();
  form = page.getByRole('dialog', { name: '编辑地区' });
  await form.getByRole('spinbutton', { name: '经度', exact: true }).fill('');
  await form.getByRole('button', { name: '确 定' }).click();
  await expect(form).not.toBeVisible();
  expect((await direct(page, 'GET', `${root}/${parent.id}`)).body.data.longitude ?? null).toBeNull();
  const downloaded = page.waitForEvent('download');
  await page.getByRole('button', { name: '导出当前筛选' }).click();
  const file = await downloaded;
  expect(file.suggestedFilename()).toBe('地区.xlsx');
  const stream = await file.createReadStream(); const chunks: Buffer[] = [];
  for await (const chunk of stream) chunks.push(chunk);
  expect(Buffer.concat(chunks).subarray(0, 2).toString()).toBe('PK');
  await row.getByRole('button', { name: '下级地区' }).click();
  await expect(page.getByText('验收顶级地区的下级地区', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '新增地区', exact: true }).click();
  form = page.getByRole('dialog', { name: '新增地区', exact: true });
  await form.getByLabel('地区名称', { exact: true }).fill('验收子地区');
  await form.getByLabel('地区编码', { exact: true }).fill('000002');
  await form.getByRole('button', { name: '确 定' }).click();
  await expect(form).not.toBeVisible();
  const child = page.getByRole('row').filter({ hasText: '验收子地区' });
  await expect(child).toBeVisible();
  await page.getByRole('button', { name: '全部顶级地区' }).click();
  await expect(row.getByRole('button', { name: /删\s*除/ })).toBeDisabled();
  await row.getByRole('button', { name: '下级地区' }).click();
  await child.getByRole('button', { name: /删\s*除/ }).click();
  await page.getByRole('tooltip').getByRole('button', { name: /删\s*除/ }).click();
  await expect(child).toHaveCount(0);
  await page.getByRole('button', { name: '全部顶级地区' }).click();
  await row.getByRole('button', { name: /删\s*除/ }).click();
  await page.getByRole('tooltip').getByRole('button', { name: /删\s*除/ }).click();
  await expect(row).toHaveCount(0);
});
