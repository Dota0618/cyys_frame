import { test, expect } from '@playwright/test';
import { login, direct, chooseScope } from './browser-support';

test('系统通知平台维护、共享内容、显示开关、纯文本详情及增改删', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await login(page, 'platform');
  const dict = '/api/admin/platform/dictionaries';
  expect((await direct(page, 'POST', dict, { id: '98311', name: '系统通知类型', systemName: 'SYSTEM_NOTICE_TYPE' })).status).toBe(200);
  expect((await direct(page, 'POST', `${dict}/98311/items`, { paramKey: 'normal', paramValue: '普通通知' })).status).toBe(200);
  await page.getByRole('menuitem').filter({ hasText: '系统通知' }).click();
  await expect(page.getByText('系统通知列表', { exact: true })).toBeVisible();
  await expect(page.getByText('阅读人数', { exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: '新增系统通知', exact: true }).click();
  const create = page.getByRole('dialog', { name: '新增系统通知' });
  await create.getByRole('button', { name: '确 定' }).click();
  await expect(create.getByText('请选择通知类型', { exact: true })).toBeVisible();
  await create.getByLabel('通知标题', { exact: true }).fill('g4-browser-notice-first');
  await create.getByRole('combobox', { name: '通知类型' }).press('ArrowDown');
  await page.locator('.ant-select-dropdown:visible').getByText('普通通知', { exact: true }).click();
  await create.getByLabel('通知正文', { exact: true }).fill('第一行\n<script>原样显示</script>');
  await expect(create.getByRole('switch', { name: '是否显示' })).not.toBeChecked();
  await create.getByRole('button', { name: '确 定' }).click();
  await expect(create).not.toBeVisible();
  const root = '/api/admin/platform/system-notices';
  const listed = await direct(page, 'GET', `${root}?title=g4-browser-notice-first`);
  expect(listed.status).toBe(200);
  const id = listed.body.data.records[0].id;
  const row = page.locator(`tr[data-row-key="${id}"]`);
  await expect(row).toContainText('隐藏');
  await chooseScope(page, '单位 A');
  await expect(row).toBeVisible();
  await chooseScope(page, '单位 B');
  await expect(row).toBeVisible();
  await row.getByRole('button', { name: /编\s*辑/ }).click();
  const edit = page.getByRole('dialog', { name: '编辑系统通知' });
  await edit.getByRole('switch', { name: '是否显示' }).click();
  await edit.getByRole('button', { name: '确 定' }).click();
  await expect(edit).not.toBeVisible();
  await expect(row).toContainText('显示');
  expect((await direct(page, 'GET', `${root}/${id}`)).body.data.visible).toBe(true);
  await row.getByRole('button', { name: /详\s*情/ }).click();
  const detail = page.getByRole('dialog', { name: 'g4-browser-notice-first' });
  await expect(detail).toContainText('<script>原样显示</script>');
  await expect(detail.locator('script')).toHaveCount(0);
  await detail.getByRole('button', { name: 'Close' }).click();
  await row.getByRole('button', { name: /删\s*除/ }).click();
  await page.getByRole('tooltip').getByRole('button', { name: /删\s*除/ }).click();
  await expect(row).toHaveCount(0);
  expect((await direct(page, 'GET', `${root}/${id}`)).status).toBe(404);
  expect(errors).toEqual([]);
});
